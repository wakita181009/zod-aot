import fs from "node:fs";
import path from "node:path";
import {
  FIN_DECL,
  generateIIFE,
  MK_VALIDATOR_DECL,
  ZOD_CONFIG_IMPORT,
  ZOD_MSG_DECLARATION,
} from "#src/core/iife.js";
import type { CompiledSchemaInfo } from "#src/core/pipeline.js";

/**
 * Generate the content of a .compiled.ts file from multiple schemas.
 */
export interface EmitterOptions {
  /**
   * When true (default), uses Object.create for Zod-compatible output.
   * When false, produces a minimal plain object (smaller bundle).
   */
  zodCompat?: boolean | undefined;
  /**
   * When true (default), emits TypeScript-only syntax (`as any`). Set to false
   * for .js/.mjs/.cjs output, which runtimes would fail to parse otherwise.
   */
  typescript?: boolean | undefined;
}

const TS_OUTPUT_RE = /\.[cm]?tsx?$/;

/** Whether an output path is a TypeScript file. */
export function isTypeScriptOutput(outputPath: string): boolean {
  return TS_OUTPUT_RE.test(outputPath);
}

export function generateCompiledFileContent(
  schemas: CompiledSchemaInfo[],
  sourceRelPath: string,
  options?: EmitterOptions,
): string {
  // A ".js" path is kept so callers targeting Node ESM can pre-convert it.
  // Other extensions are stripped rather than rewritten to ".js": webpack/rspack
  // without `resolve.extensionAlias` cannot resolve "./x.js" to x.ts.
  // getpaseo/paseo detects this exact `endsWith(".js")` shape in dist to skip
  // its own monkeypatch, so keep the expression textually intact.
  let importPath = sourceRelPath.endsWith(".js")
    ? sourceRelPath
    : sourceRelPath.replace(/\.[cm]?[jt]sx?$/, "");
  if (!importPath.startsWith(".")) {
    importPath = `./${importPath}`;
  }

  const zodCompat = options?.zodCompat !== false;
  const typescript = options?.typescript !== false;

  // A schema needs the source import when:
  //   - zodCompat: true (uses Object.create(schema))
  //   - has refEntries (fallback schemas referenced via __rf[])
  const schemasNeedingImport = schemas.filter((s) => zodCompat || s.refEntries.length > 0);

  const exports = schemas.map((schema) => {
    const needsImport = zodCompat || schema.refEntries.length > 0;
    const srcRef = typescript
      ? `(__src_${schema.exportName} as any)`
      : `__src_${schema.exportName}`;
    const schemaExpr = needsImport ? `${srcRef}.schema` : "";
    const annotation = typescript ? `: ${exportType(schema.exportName, zodCompat)}` : "";
    return `export const ${schema.exportName}${annotation} = ${generateIIFE(schemaExpr, schema, { zodCompat })};`;
  });

  const importLine = [
    ...sourceImports(schemas, schemasNeedingImport, importPath, typescript),
    ...(typescript && !zodCompat ? [TYPE_HELPER_IMPORTS] : []),
  ];

  return [
    // The emitted code is untyped JavaScript; checking it under a strict
    // tsconfig reports thousands of errors in a file the user cannot edit.
    // The export annotations still give importers real types.
    "// @ts-nocheck",
    "// AUTO-GENERATED by zod-aot — DO NOT EDIT",
    `// Source: ${sourceRelPath}`,
    "",
    ZOD_CONFIG_IMPORT,
    ZOD_MSG_DECLARATION,
    MK_VALIDATOR_DECL,
    FIN_DECL,
    "",
    ...(importLine.length > 0 ? [...importLine, ""] : []),
    ...exports,
    "",
  ].join("\n");
}

const TYPE_HELPER_IMPORTS = [
  'import type { output as __ZodOutput } from "zod";',
  'import type { CompiledSchema as __CompiledSchema } from "zod-aot";',
].join("\n");

/**
 * The type an export is annotated with. With zodCompat the validator sits on
 * the source schema's prototype chain, so it has the source export's type;
 * without it, it is a bare object holding only the four parse methods.
 */
function exportType(exportName: string, zodCompat: boolean): string {
  const src = `typeof __src_${exportName}`;
  return zodCompat ? src : `__CompiledSchema<__ZodOutput<${src}>>`;
}

/**
 * Value imports for the sources the runtime code reads, plus type-only imports
 * for the rest, which only the export annotations reference. A type-only
 * import is erased, so zodCompat: false keeps the source out of the bundle.
 */
function sourceImports(
  schemas: CompiledSchemaInfo[],
  valueSchemas: CompiledSchemaInfo[],
  importPath: string,
  typescript: boolean,
): string[] {
  const alias = (s: CompiledSchemaInfo) => `${s.exportName} as __src_${s.exportName}`;
  const lines: string[] = [];
  if (valueSchemas.length > 0) {
    lines.push(`import { ${valueSchemas.map(alias).join(", ")} } from "${importPath}";`);
  }
  const typeSchemas = typescript ? schemas.filter((s) => !valueSchemas.includes(s)) : [];
  if (typeSchemas.length > 0) {
    lines.push(`import type { ${typeSchemas.map(alias).join(", ")} } from "${importPath}";`);
  }
  return lines;
}

/**
 * Resolve the output file path for a given input file.
 */
export function resolveOutputPath(inputPath: string, outputFlag: string | undefined): string {
  if (outputFlag) {
    // If output flag ends with / or is a directory, put the compiled file inside it
    if (outputFlag.endsWith("/") || outputFlag.endsWith(path.sep)) {
      const baseName = path.basename(inputPath, path.extname(inputPath));
      return path.join(outputFlag, `${baseName}.compiled.ts`);
    }
    return outputFlag;
  }

  // Default: replace .ts with .compiled.ts
  const dir = path.dirname(inputPath);
  const baseName = path.basename(inputPath, path.extname(inputPath));
  return path.join(dir, `${baseName}.compiled.ts`);
}

/**
 * Write the compiled file content to disk.
 */
export async function writeCompiledFile(outputPath: string, content: string): Promise<void> {
  const dir = path.dirname(outputPath);
  await fs.promises.mkdir(dir, { recursive: true });
  await fs.promises.writeFile(outputPath, content, "utf-8");
}
