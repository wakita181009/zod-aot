import { describe, expect, it } from "vitest";
import {
  generateCompiledFileContent,
  isTypeScriptOutput,
  resolveOutputPath,
} from "#src/cli/emitter.js";
import type { CodeGenResult } from "#src/core/codegen/index.js";

describe("generateCompiledFileContent()", () => {
  it("generates a valid compiled file with header and Object.create wrapper", () => {
    const result: CodeGenResult = {
      code: "/* zod-aot */",
      functionDef:
        'function safeParse_test(input){\nvar __issues=[];\nif(typeof input!=="string"){__issues.push({code:"invalid_type",expected:"string",received:typeof input,path:[],message:"Expected string"});}\nif(__issues.length>0)return{success:false,error:{issues:__issues}};\nreturn{success:true,data:input};\n}',
      refCount: 0,
      usedHelpers: new Set(),
    };

    const content = generateCompiledFileContent(
      [{ exportName: "validateTest", codegenResult: result, refEntries: [] }],
      "./test.ts",
    );

    expect(content.startsWith("// @ts-nocheck\n")).toBe(true);
    expect(content).toContain("// AUTO-GENERATED by zod-aot");
    expect(content).toContain("// Source: ./test.ts");
    expect(content).toContain("export const validateTest: typeof __src_validateTest =");
    expect(content).toContain("function safeParse_test(input)");
    // Uses __mkv factory for Zod compatibility (Object.create inside __mkv)
    expect(content).toContain("__mkv(safeParse_test,(__src_validateTest as any).schema)");
    // Imports source schema (needed for zodCompat Object.create)
    expect(content).toContain('import { validateTest as __src_validateTest } from "./test"');
  });

  it("generates multiple schemas in one file", () => {
    const result1: CodeGenResult = {
      code: "/* zod-aot */",
      functionDef: "function safeParse_a(input){\nreturn{success:true,data:input};\n}",
      refCount: 0,
      usedHelpers: new Set(),
    };
    const result2: CodeGenResult = {
      code: "/* zod-aot */",
      functionDef: "function safeParse_b(input){\nreturn{success:true,data:input};\n}",
      refCount: 0,
      usedHelpers: new Set(),
    };

    const content = generateCompiledFileContent(
      [
        { exportName: "validateA", codegenResult: result1, refEntries: [] },
        { exportName: "validateB", codegenResult: result2, refEntries: [] },
      ],
      "./multi.ts",
    );

    expect(content).toContain("export const validateA");
    expect(content).toContain("export const validateB");
    expect(content).toContain("__mkv(safeParse_a,");
    expect(content).toContain("__mkv(safeParse_b,");
  });

  it("includes zod config import and __msg inside IIFE", () => {
    const result: CodeGenResult = {
      code: "/* zod-aot */",
      functionDef: "function safeParse_test(input){\nreturn{success:true,data:input};\n}",
      refCount: 0,
      usedHelpers: new Set(),
    };

    const content = generateCompiledFileContent(
      [{ exportName: "validateTest", codegenResult: result, refEntries: [] }],
      "./test.ts",
    );

    expect(content).toContain(
      'import { config as __zodAotConfig, ZodRealError as __ZodError } from "zod"',
    );
    // __msg, __mkv, __fin are declared at file level (once per file)
    expect(content).toContain("var __msg=__zodAotConfig().localeError;");
    expect(content).toContain("function __mkv(fn,schema)");
    expect(content).toContain("function __fin(e,d)");
  });

  it("always imports source schemas for Object.create", () => {
    const result: CodeGenResult = {
      code: "/* zod-aot */",
      functionDef: "function safeParse_test(input){\nreturn{success:true,data:input};\n}",
      refCount: 0,
      usedHelpers: new Set(),
    };

    const content = generateCompiledFileContent(
      [{ exportName: "validateTest", codegenResult: result, refEntries: [] }],
      "./test.ts",
    );

    // Source schemas are always imported now (for Object.create)
    expect(content).toContain('import { validateTest as __src_validateTest } from "./test"');
  });

  it("reads a compile() export's .schema but uses a plain Zod export as is", () => {
    const result: CodeGenResult = {
      code: "/* zod-aot */",
      functionDef: "function safeParse_test(input){\nreturn{success:true,data:input};\n}",
      refCount: 1,
      usedHelpers: new Set(),
    };
    const refEntries = [{ schema: {}, accessPath: '.shape["age"]' }];

    const content = generateCompiledFileContent(
      [
        { exportName: "Wrapped", exportKind: "compiled", codegenResult: result, refEntries },
        { exportName: "Plain", exportKind: "plain", codegenResult: result, refEntries },
      ],
      "./test.ts",
    );

    expect(content).toContain('var __rf=[(__src_Wrapped as any).schema.shape["age"]];');
    expect(content).toContain("__mkv(safeParse_test,(__src_Wrapped as any).schema)");
    expect(content).toContain('var __rf=[__src_Plain.shape["age"]];');
    expect(content).toContain("__mkv(safeParse_test,__src_Plain)");
  });

  it("strips TS/JS source extensions but keeps an explicit .js path", () => {
    const result: CodeGenResult = {
      code: "/* zod-aot */",
      functionDef: "function safeParse_test(input){\nreturn{success:true,data:input};\n}",
      refCount: 0,
      usedHelpers: new Set(),
    };
    const importPathFor = (source: string) => {
      const content = generateCompiledFileContent(
        [{ exportName: "validateTest", codegenResult: result, refEntries: [] }],
        source,
      );
      return content.match(/from "([^"]+)"/g)?.at(-1);
    };

    // Rewriting .ts to .js would break webpack/rspack without extensionAlias.
    for (const ext of [".ts", ".tsx", ".mts", ".cts", ".jsx", ".mjs", ".cjs"]) {
      expect(importPathFor(`./test${ext}`)).toBe('from "./test"');
    }
    // A caller that pre-converts to .js (e.g. for Node ESM) gets it verbatim.
    expect(importPathFor("./test.js")).toBe('from "./test.js"');
    expect(importPathFor("../gen/test.js")).toBe('from "../gen/test.js"');
  });
});

describe("generateCompiledFileContent() — zodCompat: false", () => {
  it("imports the source only as a type when no refEntries (enables tree-shaking)", () => {
    const result: CodeGenResult = {
      code: "/* zod-aot */",
      functionDef: "function safeParse_test(input){\nreturn{success:true,data:input};\n}",
      refCount: 0,
      usedHelpers: new Set(),
    };

    const content = generateCompiledFileContent(
      [{ exportName: "validateTest", codegenResult: result, refEntries: [] }],
      "./test.ts",
      { zodCompat: false },
    );

    expect(content).not.toContain("import { validateTest");
    expect(content).toContain('import type { validateTest as __src_validateTest } from "./test"');
    expect(content).toContain(
      "export const validateTest: __CompiledSchema<__ZodOutput<typeof __src_validateTest>> =",
    );
  });

  it("emits no types or type imports for JavaScript output", () => {
    const result: CodeGenResult = {
      code: "/* zod-aot */",
      functionDef: "function safeParse_test(input){\nreturn{success:true,data:input};\n}",
      refCount: 0,
      usedHelpers: new Set(),
    };

    const content = generateCompiledFileContent(
      [{ exportName: "validateTest", codegenResult: result, refEntries: [] }],
      "./test.js",
      { zodCompat: false, typescript: false },
    );

    expect(content).not.toContain("import type");
    expect(content).not.toContain("__src_validateTest");
    expect(content).toContain("export const validateTest = /* @__PURE__ */");
  });

  it("still imports source schemas when fallbacks exist", () => {
    const result: CodeGenResult = {
      code: "/* zod-aot */",
      functionDef:
        "function safeParse_test(input){\nvar __issues=[];\nreturn{success:true,data:input};\n}",
      refCount: 1,
      usedHelpers: new Set(),
    };

    const content = generateCompiledFileContent(
      [
        {
          exportName: "validateUser",
          codegenResult: result,
          refEntries: [{ schema: {}, accessPath: '.shape["slug"]' }],
        },
      ],
      "./schemas.ts",
      { zodCompat: false },
    );

    expect(content).toContain('import { validateUser as __src_validateUser } from "./schemas"');
    expect(content).toContain(
      "export const validateUser: __CompiledSchema<__ZodOutput<typeof __src_validateUser>> = /* @__PURE__ */",
    );
    expect(content).toContain("__mkv(safeParse_test,null)");
  });
});

describe("resolveOutputPath()", () => {
  it("defaults to .compiled.ts when no output flag", () => {
    const result = resolveOutputPath("src/schemas.ts", undefined);
    expect(result).toBe("src/schemas.compiled.ts");
  });

  it("uses output flag as-is when it's a file path", () => {
    const result = resolveOutputPath("src/schemas.ts", "out/validators.ts");
    expect(result).toBe("out/validators.ts");
  });

  it("puts compiled file inside directory when output ends with /", () => {
    const result = resolveOutputPath("src/schemas.ts", "out/");
    expect(result).toContain("out/");
    expect(result).toContain("schemas.compiled.ts");
  });
});

describe("isTypeScriptOutput()", () => {
  it("detects TypeScript extensions", () => {
    for (const p of ["a.ts", "a.mts", "a.cts", "a.tsx", "dir/a.compiled.ts"]) {
      expect(isTypeScriptOutput(p)).toBe(true);
    }
    for (const p of ["a.js", "a.mjs", "a.cjs", "a.jsx", "a.d"]) {
      expect(isTypeScriptOutput(p)).toBe(false);
    }
  });
});
